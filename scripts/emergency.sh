#!/usr/bin/env bash
# Run the tracker on this machine, in a container, when the usual host can't.
#
# The deployment this app was built for has several things that can fail on a
# Friday night and cannot be fixed from a games table: the LXC host, the
# Cloudflare Tunnel, the house internet, DNS. This script is the answer to all
# four — one container on the laptop that is already in the room, serving the
# phones that are already on the wifi.
#
#   ./scripts/emergency.sh prepare     # DO THIS BEFORE THE NIGHT (needs internet)
#   ./scripts/emergency.sh start       # on the night: brings it up, prints the URLs
#   ./scripts/emergency.sh status
#   ./scripts/emergency.sh logs
#   ./scripts/emergency.sh backup      # snapshot the database mid-event
#   ./scripts/emergency.sh stop
#   ./scripts/emergency.sh seed FILE   # start from a production backup instead of empty
#
# `prepare` is the whole point of the design: it builds the image AND saves it
# to a tarball in the kit directory, so `start` needs no registry, no pip and no
# network at all. An emergency plan that only works while the internet does is
# not an emergency plan.
#
# Everything that must survive — the event config, the database, backups — lives
# in the kit directory on the host ($COMMANDER_KIT, default
# ~/commander-tracker-emergency), bind-mounted at /data. Destroying the
# container never destroys a night's results.
set -euo pipefail

IMAGE=${COMMANDER_IMAGE:-localhost/commander-tracker:emergency}
CONTAINER=${COMMANDER_CONTAINER:-commander-tracker-emergency}
KIT=${COMMANDER_KIT:-$HOME/commander-tracker-emergency}
PORT=${COMMANDER_PORT:-8000}
REPO=$(cd -- "$(dirname -- "$0")/.." && pwd)
IMAGE_TAR="$KIT/image.tar"

die() { printf '\nerror: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }
rule() { printf '%s\n' "------------------------------------------------------------"; }

need_podman() {
    command -v podman >/dev/null 2>&1 || die \
"podman is not installed. On Fedora: sudo dnf install podman
Nothing else is needed — the image carries Python and every dependency."
}

# Hex from /dev/urandom via coreutils only: a machine that cannot run this has
# no shell either, which is more than can be said for python3 or openssl on a
# borrowed laptop.
rand_hex() { od -vAn -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }

# --- the kit directory ------------------------------------------------------

ensure_kit() {
    mkdir -p "$KIT/config" "$KIT/backups"

    if [ ! -f "$KIT/config/event.yaml" ]; then
        # A local config/event.yaml is the real event — roster, prizes, the
        # owner's tiebreaks — and is worth far more here than the example.
        if [ -f "$REPO/config/event.yaml" ]; then
            cp "$REPO/config/event.yaml" "$KIT/config/event.yaml"
            say "config: copied your config/event.yaml into $KIT/config/"
        else
            cp "$REPO/config/event.example.yaml" "$KIT/config/event.yaml"
            say "config: seeded $KIT/config/event.yaml from the EXAMPLE."
            say "        Edit the roster and prizes in it, or paste the real one over it."
        fi
    fi

    if [ ! -f "$KIT/.env" ]; then
        # Nothing in app/ reads a .env file (a known gap, see handoff/BUILD-LOG
        # KG-13) — podman's --env-file does the reading, which is why this works
        # here and not from a bare `uvicorn`.
        umask 077
        cat > "$KIT/.env" <<EOF
# Generated by scripts/emergency.sh on $(date '+%Y-%m-%d %H:%M'). Local use only.
# The passcode is what trackers type at /login. Change it if you like; restart after.
TRACKER_PASSCODE=$(rand_hex 2)-$(rand_hex 2)
SESSION_SECRET=$(rand_hex 32)
EOF
        say "auth:   generated a passcode and session secret in $KIT/.env"
    fi
}

passcode() { sed -n 's/^TRACKER_PASSCODE=//p' "$KIT/.env" | head -1; }

# --- image ------------------------------------------------------------------

build_image() {
    # --format docker, not the OCI default: podman drops HEALTHCHECK from an OCI
    # image, and `status` reporting health is most of this script's value when
    # something is wrong at 8pm.
    say "building $IMAGE (needs internet, a few minutes the first time)..."
    podman build --format docker -t "$IMAGE" -f "$REPO/Containerfile" "$REPO"
}

have_image() { podman image exists "$IMAGE"; }

ensure_image() {
    have_image && return 0
    if [ -f "$IMAGE_TAR" ]; then
        say "loading the saved image from $IMAGE_TAR (no network needed)..."
        podman load -i "$IMAGE_TAR" >/dev/null
        have_image && return 0
    fi
    say "no image and no saved tarball — building one now."
    say "If this machine is offline, this is the step that fails: run"
    say "'./scripts/emergency.sh prepare' on a connected machine beforehand."
    build_image
}

# --- http probing -----------------------------------------------------------

http_code() {
    if command -v curl >/dev/null 2>&1; then
        curl -s -o /dev/null -w '%{http_code}' --max-time 3 "$1" 2>/dev/null || echo 000
    else
        podman exec "$CONTAINER" python -c "
import sys, urllib.request, urllib.error
try:
    print(urllib.request.urlopen(sys.argv[1], timeout=3).status)
except urllib.error.HTTPError as e:
    print(e.code)
except Exception:
    print('000')
" "$1" 2>/dev/null || echo 000
    fi
}

wait_until_up() {
    local i
    for i in $(seq 1 40); do
        [ "$(http_code "http://127.0.0.1:$PORT/login")" = "200" ] && return 0
        podman container exists "$CONTAINER" || return 1
        [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER")" = "true" ] || return 1
        sleep 1
    done
    return 1
}

lan_addresses() {
    ip -4 -o addr show scope global 2>/dev/null |
        awk '{split($4, a, "/"); print a[1]}'
}

print_access() {
    local code
    rule
    say "Commander Tracker is up on this machine."
    rule
    say "On this laptop:"
    say "  entry    http://localhost:$PORT/entry"
    say "  admin    http://localhost:$PORT/admin"
    say "  display  http://localhost:$PORT/display     <- project this"
    say "  results  http://localhost:$PORT/results"
    say ""
    local addr
    for addr in $(lan_addresses); do
        say "For the trackers' phones on the same wifi:  http://$addr:$PORT/entry"
    done
    say ""
    say "Passcode: $(passcode)"
    say "          (also in $KIT/.env — write it on a card, every tracker needs it)"
    say ""
    say "Database: $KIT/commander.db"
    say "Config:   $KIT/config/event.yaml   (edited live; no restart needed)"
    rule

    # firewalld blocks the phones while localhost works perfectly, which is the
    # most confusing possible failure in a room full of people waiting. The hint
    # prints unless the port is *confirmed* open: an unprivileged
    # `firewall-cmd --query-port` can fail to get an answer at all, and silence
    # on the strength of that is how the room ends up debugging the app instead
    # of the firewall.
    if command -v firewall-cmd >/dev/null 2>&1 &&
       [ "$(firewall-cmd --query-port="$PORT/tcp" 2>/dev/null)" != "yes" ]; then
        say "If a phone cannot load that address, the firewall is the first suspect."
        say "To open the port until this machine reboots:"
        say ""
        say "  sudo firewall-cmd --add-port=$PORT/tcp"
        rule
    fi

    code=$(http_code "http://127.0.0.1:$PORT/display")
    [ "$code" = "200" ] || say "note: /display answered $code, not 200 — check 'logs'."
}

# --- commands ---------------------------------------------------------------

cmd_prepare() {
    need_podman
    ensure_kit
    build_image
    say "saving the image to $IMAGE_TAR so the night needs no network..."
    podman save -o "$IMAGE_TAR" "$IMAGE"
    rule
    say "Ready. The kit is $KIT — it now holds the image, the event config,"
    say "and the passcode. On the night, with or without internet:"
    say ""
    say "  $REPO/scripts/emergency.sh start"
    say ""
    say "Rehearse it once tonight: start, record a turn at /entry, watch /display"
    say "update, then 'stop'. A plan nobody has run is a plan nobody has."
    rule
}

cmd_start() {
    need_podman
    ensure_kit
    ensure_image

    if podman container exists "$CONTAINER"; then
        if [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER")" = "true" ]; then
            say "already running."
            print_access
            return 0
        fi
        # A stopped container of the same name would block the run; its data is
        # in the kit directory, not in it, so removing it loses nothing.
        podman rm "$CONTAINER" >/dev/null
    fi

    say "starting $CONTAINER on port $PORT..."
    # --tz=local so backup filenames and log lines read in the room's clock.
    # :Z relabels the kit directory for SELinux, which Fedora enforces.
    # Rootless podman maps container root to this user, so files written into
    # the kit directory stay owned by you and are readable after the event.
    podman run -d \
        --name "$CONTAINER" \
        --env-file "$KIT/.env" \
        -v "$KIT:/data:Z" \
        -p "$PORT:8000" \
        --tz=local \
        --restart=on-failure:10 \
        "$IMAGE" >/dev/null

    if ! wait_until_up; then
        say ""
        say "It did not come up. The last of its output:"
        rule
        podman logs --tail 30 "$CONTAINER" 2>&1 || true
        rule
        die "see above. 'podman logs $CONTAINER' has the rest."
    fi
    print_access
}

cmd_stop() {
    need_podman
    podman container exists "$CONTAINER" || { say "not running."; return 0; }
    podman stop "$CONTAINER" >/dev/null
    podman rm "$CONTAINER" >/dev/null
    say "stopped. The database and config are still in $KIT."
}

cmd_status() {
    need_podman
    say "kit:       $KIT"
    say "image:     $IMAGE $(have_image && echo '(present)' || echo '(MISSING)')"
    say "saved tar: $([ -f "$IMAGE_TAR" ] && echo "$IMAGE_TAR" || echo 'none — run prepare')"
    if [ -f "$KIT/commander.db" ]; then
        say "database:  $KIT/commander.db ($(du -h "$KIT/commander.db" | cut -f1), last written $(date -r "$KIT/commander.db" '+%Y-%m-%d %H:%M'))"
    else
        say "database:  none yet — it is created on first start"
    fi
    if ! podman container exists "$CONTAINER"; then
        say "container: not created"
        return 0
    fi
    say "container: $(podman inspect -f '{{.State.Status}}' "$CONTAINER") (health: $(podman inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}n/a{{end}}' "$CONTAINER"))"
    [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER")" = "true" ] || return 0
    local path
    for path in /login /display /entry; do
        say "  $path -> $(http_code "http://127.0.0.1:$PORT$path")"
    done
    say "passcode:  $(passcode)"
}

cmd_logs() {
    need_podman
    podman container exists "$CONTAINER" || die "nothing to show: the container does not exist."
    podman logs -f --tail 50 "$CONTAINER"
}

cmd_backup() {
    need_podman
    podman container exists "$CONTAINER" &&
        [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER")" = "true" ] ||
        die "start it first — this takes the snapshot through the running app."
    # The app's own backup_database(): SQLite's backup API, so a snapshot taken
    # while two trackers are saving is still consistent. A plain cp of a WAL
    # database is not.
    podman exec "$CONTAINER" python -c \
        'from app.db import backup_database; print(backup_database())'
    say "...which is $KIT/backups/ on this machine."
}

cmd_seed() {
    local src=${1:-}
    [ -n "$src" ] || die "usage: $0 seed /path/to/commander.db"
    [ -f "$src" ] || die "no such file: $src"
    need_podman
    if podman container exists "$CONTAINER" &&
       [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER")" = "true" ]; then
        die "stop it first: '$0 stop'. Replacing the database under a running app
would leave the open connections reading a file that no longer exists."
    fi
    ensure_kit
    rule
    say "This will REPLACE the emergency database with a copy of:"
    say "  $src"
    say "  ($(du -h "$src" | cut -f1), modified $(date -r "$src" '+%Y-%m-%d %H:%M'))"
    if [ -f "$KIT/commander.db" ]; then
        say ""
        say "The file it overwrites, and what will be kept as a .displaced copy:"
        say "  $KIT/commander.db ($(du -h "$KIT/commander.db" | cut -f1), modified $(date -r "$KIT/commander.db" '+%Y-%m-%d %H:%M'))"
    else
        say ""
        say "There is no emergency database yet, so nothing is lost."
    fi
    rule
    printf 'Type yes to go ahead: '
    read -r answer
    # A decline is not a failure: say so and exit clean.
    if [ "$answer" != "yes" ]; then
        say "nothing changed."
        return 0
    fi
    if [ -f "$KIT/commander.db" ]; then
        mv "$KIT/commander.db" "$KIT/commander.db.displaced.$(date '+%Y%m%d-%H%M%S')"
    fi
    # The -wal and -shm of the old database describe a file that is now gone.
    rm -f "$KIT/commander.db-wal" "$KIT/commander.db-shm"
    cp "$src" "$KIT/commander.db"
    say "seeded. Start it with '$0 start'."
}

usage() {
    sed -n '2,/^set -euo/p' "$0" | sed 's/^# \{0,1\}//; /^set -euo/d'
}

case "${1:-}" in
    prepare) cmd_prepare ;;
    start)   cmd_start ;;
    stop)    cmd_stop ;;
    restart) cmd_stop; cmd_start ;;
    status)  cmd_status ;;
    logs)    cmd_logs ;;
    backup)  cmd_backup ;;
    seed)    shift; cmd_seed "${1:-}" ;;
    ""|-h|--help|help) usage ;;
    *) die "unknown command: $1. Try --help." ;;
esac
